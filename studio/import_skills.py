#!/usr/bin/env python3
"""Import the owner's Ai-Animation skills into this repo, inside the studio harness.

    git clone --depth 1 https://github.com/manikk90/Ai-Animation /path/to/ai-animation
    python3 studio/import_skills.py /path/to/ai-animation

For every `skills/<name>/SKILL.md`, and for `daksh-ai/` with its engine, harness and tools, this writes
`.claude/skills/<name>/`. The original text stays whole; a short harness block goes under the title. The block says
where the words come from and which studio gates apply, plus the rights and fact checks that apply and the delivery
rule. The full contract is `studio/SKILL_HARNESS.md`.

It also writes:
- `studio/IMPORTED_SKILLS.json`: the registry the style menu, the agents and the tests read
- `third_party/ai-animation/`: the licence and the source note

Re-run it after an upstream change: everything is regenerated from the source. Skills that disappeared upstream are
reported, not deleted. To change how a skill runs here, change the tables below or the harness, never the copies.
Standard library only.
"""
