def kind_of(name: str) -> str:
    return next((k for k, names in KIND.items() if name in names), "clip")


def flags_of(name: str) -> list[str]:
    return [f for f, names in FLAGS.items() if name in names]


def parse(md: str, path: Path) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n", md, re.S)
    if not m:
        raise SystemExit(f"{path}: no frontmatter")
    front = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = json.loads(value)
        front[key.strip()] = value
    if not front.get("name") or not front.get("description"):
        raise SystemExit(f"{path}: frontmatter needs name and description")
    return front, md[m.end():]


def block(name: str, source: str, commit: str, kind: str, flags: list[str]) -> str:
    lines = [
        MARK,
        f"> **Studio harness: read this first.** Imported from the owner's [Ai-Animation]({UPSTREAM}) repo "
        f"(`{source}`, commit `{commit}`), MIT © 2026 aansh.ai: see "
        "[`third_party/ai-animation/LICENSE`](../../../third_party/ai-animation/LICENSE). In this repo it runs inside "
        "the studio. Read `studio/LEARNINGS.md` and [`studio/SKILL_HARNESS.md`](../../../studio/SKILL_HARNESS.md) "
        "first; where they disagree with the steps below, they win.",
        f"> - **Words:** {WORDS[kind]}",
        "> - **Before you start:** run `python3 studio/check_env.py`. It shows what works in this session: rendering, "
        "word timing, Whisper and ElevenLabs.",
        "> - **Preview (Gate 3):** before the full render, send 3 numbered frames at 3 timecodes (the hook, the "
        "middle, the end), plus a 20–30 s music sketch when the skill adds music, and wait for the owner's OK. This "
        "replaces any contact sheet, stills or snapshot step below. For a canvas page, "
        "`node studio/render_canvas.cjs <page> <prefix> --stills 1,6,11` makes the frames, and the same script renders "
        "the video locally.",
        *[f"> - {FLAG_LINES[f]}" for f in flags],
    ]
    if kind != "visual":
        lines.append("> - **Word timing:** never guess. For known words (a script, lyrics, the locked dialogue), "
                     "`studio/word_timing.py` aligns them offline. For unknown words, the doctor shows whether "
                     "Whisper or alignment can run; if not, ask the owner for a transcript. Say which route you used.")
    lines.append("> - **Deliver:** to `projects/<slug>/final/`, then send exactly 2 files with `studio/deliver.py`: "
                 "the final video, and one zip with everything else. Keep any WhatsApp copy in `final/` unless the "
                 "owner asks for it.")
    return "\n".join(lines) + "\n"


def render(front: dict, body: str, harness: str, hint: str) -> str:
    head = ["---", f"name: {front['name']}", f"description: {json.dumps(front['description'], ensure_ascii=False)}"]
    if hint:
        head.append(f"argument-hint: {json.dumps('[' + hint + ']', ensure_ascii=False)}")
    head.append("---")
    m = re.search(r"^# .+\n", body, re.M)
    if not m:
        raise SystemExit(f"{front['name']}: no title line")
    return "\n".join(head) + "\n" + body[:m.end()] + "\n" + harness + body[m.end():]


def describe(name: str, front: dict, body: str, source: str, commit: str) -> dict:
    title = re.search(r"^# (.+)$", body, re.M).group(1).strip()
    inp = re.search(r"^\*\*Input:\*\*\s*(.+?)\.?$", body, re.M)
    group = re.search(r"·\s*([^·\n]+?)\s*$", body.strip())
    return {
        "name": name,
        "title": title,
        "group": "Animated videos (with engine)" if name == ENGINE else (group.group(1) if group else "Other"),
        "input": inp.group(1) if inp else "a voice recording (MP3), and the exact script if you have one",
        "kind": kind_of(name),
        "flags": flags_of(name),
        "source": source,
        "commit": commit,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Import the Ai-Animation skills into .claude/skills/ inside the studio harness.")
    ap.add_argument("source", help="a clone of https://github.com/manikk90/Ai-Animation")
    a = ap.parse_args(argv)
    src = Path(a.source).resolve()
    try:
        commit = subprocess.run(["git", "-C", str(src), "rev-parse", "--short", "HEAD"], capture_output=True,
                                text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    found = sorted(p.parent for p in (src / "skills").glob("*/SKILL.md"))
    if (src / ENGINE / "SKILL.md").is_file():
        found.append(src / ENGINE)
    if not found:
        raise SystemExit(f"no skills found under {src}")
    ours = {p.name for p in SKILLS.iterdir() if p.is_dir()} if SKILLS.is_dir() else set()
    old = {e["name"] for e in json.loads(REGISTRY.read_text(encoding="utf-8"))} if REGISTRY.exists() else set()
    entries = []
    for folder in found:
        md = (folder / "SKILL.md").read_text(encoding="utf-8")
        front, body = parse(md, folder / "SKILL.md")
        name = front["name"]
        if name != folder.name:
            raise SystemExit(f"{folder}: frontmatter name {name!r} differs from the folder name")
        if name in ours and name not in old:
            raise SystemExit(f"{name}: a studio skill with this name already exists; rename before importing")
        source = f"{folder.relative_to(src).as_posix()}/SKILL.md"
        info = describe(name, front, body, source, commit)
        dest = SKILLS / name
        if dest.exists():
            shutil.rmtree(dest)
        if name == ENGINE:
            shutil.copytree(folder, dest, ignore=shutil.ignore_patterns("node_modules", "renders", "snapshots", "*.wav"))
        else:
            dest.mkdir(parents=True)
        harness = block(name, source, commit, info["kind"], info["flags"])
        (dest / "SKILL.md").write_text(render(front, body, harness, info["input"]), encoding="utf-8")
        entries.append(info)
    REGISTRY.write_text(json.dumps(sorted(entries, key=lambda e: e["name"]), ensure_ascii=False, indent=1) + "\n",
                        encoding="utf-8")
    THIRD.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src / "LICENSE", THIRD / "LICENSE")
    (THIRD / "README.md").write_text(
        "# Ai-Animation skills (third-party, MIT)\n\n"
        f"The format skills in `.claude/skills/` listed in `studio/IMPORTED_SKILLS.json` come from the owner's "
        f"[Ai-Animation]({UPSTREAM}) repo, commit `{commit}`. Upstream, the skills are by aansh.ai "
        "([aanshai.vercel.app/skills](https://aanshai.vercel.app/skills)), MIT licensed: see `LICENSE` here.\n\n"
        f"- Imported on {date.today().isoformat()} at the owner's request, by `studio/import_skills.py`.\n"
        "- Each copy keeps its original text and adds a studio-harness block under its title. The contract is "
        "`studio/SKILL_HARNESS.md`.\n"
        "- `daksh-ai` comes with its engine, harness and tools. Its `template/assets/gsap.min.js` keeps GSAP's own "
        "licence header.\n"
        "- To update, re-run `python3 studio/import_skills.py <Ai-Animation clone>`. Never edit the copies by hand.\n",
        encoding="utf-8")
    names = {e["name"] for e in entries}
    for gone in sorted(old - names):
        print(f"note: {gone} is no longer upstream; its copy was left in place, remove it on purpose if wanted")
    for e in entries:  # a new upstream skill falls back to "clip"; say so when its input is not footage
        if e["kind"] == "clip" and not re.search(r"clip|video|recording|footage|folder", e["input"], re.I):
            print(f"note: {e['name']} defaults to kind 'clip' but takes {e['input']!r}; classify it in KIND")
    print(f"{len(entries)} skills imported from {src.name}@{commit} -> {SKILLS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
